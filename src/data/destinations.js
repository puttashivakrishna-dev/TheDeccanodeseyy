  `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(destination.mapQuery)}`;

export function directionsLink(fromQuery, destination) {
  const params = new URLSearchParams({
    api: '1',
    origin: fromQuery,
    destination: destination.mapQuery,
  });
  return `https://www.google.com/maps/dir/?${params.toString()}`;
}

export function routeLink(originQuery, waypointQueries) {
  const params = new URLSearchParams({ api: '1', origin: originQuery });
  if (waypointQueries.length > 1) {
    params.set('destination', waypointQueries[waypointQueries.length - 1]);
    params.set('waypoints', waypointQueries.slice(0, -1).join('|'));
  } else {
    params.set('destination', waypointQueries[0] || originQuery);
  }
  params.set('travelmode', 'driving');
  return `https://www.google.com/maps/dir/?${params.toString()}`;
}